import pandas as pd, glob, os, numpy as np
T, C = [], []
for d in sorted(glob.glob('artifacts/bt_combo/*/')):
    t = pd.read_parquet(os.path.join(d, 'trades.parquet'))
    c = pd.read_parquet(os.path.join(d, 'candidates.parquet'))
    t['window'] = os.path.basename(d.rstrip('/'))
    c['window'] = os.path.basename(d.rstrip('/'))
    T.append(t); C.append(c)
T = pd.concat(T, ignore_index=True)
C = pd.concat(C, ignore_index=True)
T['win'] = T['usd'] > 0

print('=== TRADES (executed) ===')
print(f'total={len(T):,}  winrate={T["win"].mean():.1%}  pnl=${T["usd"].sum():,.0f}')
print()
print('By window:')
print(T.groupby('window').agg(n=('usd','size'), wr=('win','mean'), pnl=('usd','sum')).to_string())
print()
print('By family:')
g = T.groupby('family').agg(n=('usd','size'), wr=('win','mean'), pnl=('usd','sum'), avg=('usd','mean'))
print(g.sort_values('pnl', ascending=False).to_string())
print()
print('By session:')
print(T.groupby('session').agg(n=('usd','size'), wr=('win','mean'), pnl=('usd','sum')).to_string())
print()
print('By hour:')
h = T.groupby('hour').agg(n=('usd','size'), wr=('win','mean'), pnl=('usd','sum'))
print(h.to_string())
print()
print('intrinsic_score vs outcome:')
T['score_bin'] = pd.cut(T['intrinsic_score'], bins=[0, 0.45, 0.55, 0.65, 0.75, 1.0])
print(T.groupby('score_bin', observed=True).agg(n=('usd','size'), wr=('win','mean'), pnl=('usd','sum')).to_string())
print()
print('kl_weight vs outcome:')
T['klw_bin'] = pd.cut(T['kl_weight'], bins=[0, 0.25, 0.4, 0.55, 0.7, 1.01])
print(T.groupby('klw_bin', observed=True).agg(n=('usd','size'), wr=('win','mean'), pnl=('usd','sum')).to_string())
print()
print('=== CANDIDATES (all scanned) ===')
print(f'total={len(C):,}  accepted={C["accepted"].sum():,} ({C["accepted"].mean():.1%})')
print()
print('Block reasons (top 10):')
print(C[~C['accepted']]['block_reason'].value_counts().head(10).to_string())
print()
print('Block reasons x family:')
bl = C[~C['accepted']].groupby(['family','block_reason']).size().unstack(fill_value=0)
print(bl.to_string())
